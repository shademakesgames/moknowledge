// Optional browser QA: requires Playwright and its Chromium browser.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
(async () => {
  const browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_CHANNEL || undefined });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
  const page = await context.newPage(); const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  await fs.mkdir('docs/screenshots', { recursive: true });
  await page.goto(process.env.APP_URL || 'http://localhost:3001/knowledge');
  await page.getByRole('heading', { name: 'Knowledge', exact: true }).waitFor();
  await page.screenshot({ path: 'docs/screenshots/builder.png', fullPage: true });
  await page.getByLabel('Company website', { exact: true }).fill('https://account-it.net/');
  await page.getByRole('button', { name: 'Build knowledge', exact: false }).click();
  await page.getByText('Your draft is ready.', { exact: false }).waitFor({ timeout: 65000 });
  await page.getByLabel('Company name', { exact: true }).fill('Account-it Consulting — reviewed');
  await page.getByRole('button', { name: 'Save knowledge', exact: false }).click();
  await page.getByText('Saved Account-it Consulting — reviewed', { exact: false }).waitFor();
  await page.screenshot({ path: 'docs/screenshots/review.png', fullPage: true });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download JSON' }).click();
  const download = await downloadPromise;
  const exportPath = await download.path();
  const exported = JSON.parse(await fs.readFile(exportPath, 'utf8'));
  assert.equal(exported.sections.foundation.name.value, 'Account-it Consulting — reviewed');
  assert.equal(exported.sections.foundation.name.status, 'user_provided');
  assert.ok(exported.sections.foundation.name.sources.length);
  await page.getByRole('link', { name: 'Knowledge library', exact: false }).click();
  await page.getByRole('button', { name: 'Account-it Consulting — reviewed', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: 'Account-it Consulting — reviewed', exact: true }).waitFor();
  await page.getByLabel('Search knowledge bases').fill('no matching result');
  await page.getByText('No matching companies').waitFor();
  await page.getByLabel('Search knowledge bases').fill('');
  await page.getByRole('button', { name: 'Table', exact: true }).click();
  assert.equal(await page.locator('tbody tr').count(), 1);
  await page.getByRole('button', { name: 'Details', exact: true }).click();
  await page.getByRole('button', { name: 'Key people', exact: false }).click();
  await page.getByRole('button', { name: 'Close details' }).click();
  await page.getByRole('link', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Company name', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('Company name', { exact: true }).inputValue(), 'Account-it Consulting — reviewed');
  await page.getByLabel('Overview', { exact: true }).fill('Reviewed accounting services overview.');
  await page.getByRole('button', { name: 'Save knowledge', exact: false }).click();
  await page.getByText('version 2.', { exact: false }).waitFor();
  await page.getByRole('link', { name: 'Knowledge library', exact: false }).click();
  await page.getByRole('heading', { name: 'Knowledge library', exact: true }).waitFor();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'docs/screenshots/library.png', fullPage: false });
  const imported = structuredClone(exported); imported.id = crypto.randomUUID(); imported.sections.foundation.name.value = 'QA imported company';
  await page.locator('input[type=file]').setInputFiles({ name: 'import.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(imported)) });
  await page.getByText('Imported QA imported company.').waitFor();
  await page.getByRole('button', { name: 'Table', exact: true }).click();
  assert.equal(await page.locator('tbody tr').count(), 2);
  await page.locator('tbody tr').filter({ hasText: 'QA imported company' }).getByRole('button', { name: 'Delete' }).click();
  assert.equal(await page.locator('tbody tr').count(), 1);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Cards', exact: true }).click();
  await page.screenshot({ path: 'docs/screenshots/library-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile library overflows');
  await page.getByRole('link', { name: 'Knowledge builder', exact: false }).click();
  await page.getByRole('heading', { name: 'Knowledge', exact: true }).waitFor();
  await page.screenshot({ path: 'docs/screenshots/builder-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile builder overflows');
  const response = await context.request.post((process.env.APP_URL || 'http://localhost:3001/knowledge').replace(/\/knowledge$/, '/api/scrape'), { data: { url: 'http://127.0.0.1/' } });
  assert.equal(response.status(), 422);
  assert.match((await response.json()).error, /not allowed/);
  assert.deepEqual(errors, []);
  console.log('PASS: live crawl, edit, save, reload, search, cards/table/details, export, import, delete, mobile layout, private-address rejection, and no browser exceptions.');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
